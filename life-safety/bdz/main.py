"""Проверочный расчёт БДЗ по БЖД, вариант 1.

Задание 1 — интегральная балльная оценка тяжести и напряжённости труда
(формулы 1.1 и 1.2 методички «БДЗ - часть 1»).
Задание 2 — сравнение пробы воды с ПДК и сумма C/ПДК для веществ 1–2 классов (формула 2.1).
Печатает все промежуточные числа, которые стоят в отчёте.
"""

from fractions import Fraction as F

SHIFT = 480  # продолжительность смены, мин


def integral(scores):
    """T = x_max + (6 - x_max) * (сумма без одного x_max) / (6 * (N - 1)).

    scores — список (название, x_ф); N — число факторов (освещённость — один фактор
    из двух строк, поэтому N передаём отдельно)."""
    xs = [x for _, x in scores]
    x_max = max(xs)
    rest = sum(xs) - x_max  # вычитаем только ОДИН максимальный балл
    return x_max, sum(xs), rest


def category(t):
    # шкала из методички (стр. 5): до 1,8; 1,8…3,3; 3,4…4,5; 4,6…5,3; 5,4…5,9; более 5,9
    for upper, cat in ((1.8, 1), (3.3, 2), (4.5, 3), (5.3, 4), (5.9, 5)):
        if t <= upper:
            return cat
    return 6


def task1():
    print("Задание 1. Инженер-разработчик, вариант 1")
    # (фактор, балл X по табл. 1.1, время действия, мин; None — весь день)
    factors = [
        ("Температура 18…20 °C (тёплый период)", 1, 420),
        ("Освещённость: размер объекта < 0,3 мм", 3, 420),
        ("Освещённость: разряд зрительной работы 2", 3, 420),
        ("Шум: превышение ПДУ на 2 дБА", 3, 240),
        ("РМ стационарное, поза свободная, груз до 5 кг", 1, None),
        ("Работа в утреннюю смену", 1, None),
        ("Непрерывная работа 8 ч", 3, None),
        ("Сосредоточенное наблюдение 30 %", 2, None),
        ("Обоснованный режим труда и отдыха с музыкой и гимнастикой", 1, None),
        ("НЭН: простые действия по индивидуальному плану", 1, None),
    ]
    scores = []
    for name, x, t in factors:
        k = F(t, SHIFT) if t else F(1)
        xf = x * k
        scores.append((name, xf))
        tt = f"{t}" if t else "—"
        print(f"  {name:58s} X={x}  t={tt:>3}  t_уд={float(k):.3f}  X_ф={float(xf):.3f}")

    n_factors = 9  # освещённость (размер + разряд) — один фактор, как в примере методички
    x_max, total, rest = integral(scores)
    t = x_max + (6 - x_max) * rest / (6 * (n_factors - 1))
    print(f"  ΣX_ф = {float(total):.3f}, X_max = {float(x_max)}, ΣX_ф без X_max = {float(rest):.3f}")
    print(f"  N = {n_factors}: T = {float(x_max)} + (6 − {float(x_max)})·{float(rest):.3f} / (6·{n_factors - 1})"
          f" = {float(t):.4f} → категория {category(float(t))}")

    # проверка устойчивости вывода к спорным решениям
    print("  Проверка устойчивости:")
    t10 = x_max + (6 - x_max) * rest / (6 * (10 - 1))
    print(f"    освещённость как два фактора (N = 10): T = {float(t10):.4f} → {category(float(t10))}")
    alt = [(n, (F(2) if n.startswith("Непрерывная") else x)) for n, x in scores]
    xm2, _, r2 = integral(alt)
    t2 = xm2 + (6 - xm2) * r2 / (6 * (n_factors - 1))
    print(f"    непрерывная работа 2 балла: X_max = {float(xm2)}, T = {float(t2):.4f} → {category(float(t2))}")
    print()


def task2():
    print("Задание 2. Проба воды, вариант 1")
    # вещество: (C факт, ПДК, ЛПВ, класс опасности); ПДК None — «отсутствие»
    sample = {
        "Алюминий": (0.4, 0.5, "с.-т.", 2),
        "Бериллий": (0.0001, 0.0002, "с.-т.", 1),
        "Бутилен": (0.15, 0.2, "орг.", 3),
        "Ацетон": (2.0, 2.2, "общ.", 3),
        "Хлор активный": (0.0001, None, "общ.", 3),
    }
    s = 0.0
    for name, (c, pdk, lpv, cls) in sample.items():
        if pdk is None:
            print(f"  {name:14s} C={c:<7g} ПДК=отсутствие  {lpv:6s} класс {cls}: вещество обнаружено → норматив не выполнен")
            continue
        r = c / pdk
        mark = "≤ ПДК" if c <= pdk else "> ПДК"
        print(f"  {name:14s} C={c:<7g} ПДК={pdk:<7g} {lpv:6s} класс {cls}: C/ПДК = {r:.3f} ({mark})")
        if cls in (1, 2):
            s += r
    print(f"  Σ C/ПДК для 1–2 классов = {s:.2f} → {'≤ 1, норма' if s <= 1 else '> 1, норма не выполнена'}")


if __name__ == "__main__":
    task1()
    task2()
