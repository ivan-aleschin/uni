// ЛР7, метрики Лоренца и Кидда. Вариант 1, задача 5:
// определить понятие «Абонент телефонной сети» (номер телефона, фамилия,
// номер паспорта), на его основе определить понятие «Задолженность»
// (добавляется поле «Долг по оплате») и вывести данные абонента
// с максимальным долгом среди всех абонентов.
//
// Комментарии в расчёт метрик не входят: листинг в README.md приведён
// без них, и номера строк в таблицах относятся именно к тому листингу.
using System;

namespace Lab7
{
    // «Абонент телефонной сети» — базовый класс.
    // Поля protected, а не private: наследнику они понадобятся напрямую
    // (так же сделано с x, y в классе Точка из примера методички).
    class Абонент
    {
        protected int номерТелефона;   // семизначное целое число
        protected string фамилия;      // строка до 20 символов
        protected long номерПаспорта;  // длинное целое число
        public Абонент(int номерТелефона, string фамилия, long номерПаспорта)
        {
            this.номерТелефона = номерТелефона;
            this.фамилия = фамилия;
            this.номерПаспорта = номерПаспорта;
        }
        // Метод вывода в базовом классе обычный: не virtual и не abstract,
        // как в примере «Геометрия».
        public void Показать()
        {
            Console.WriteLine("Телефон: {0}, фамилия: {1}, паспорт: {2}", номерТелефона, фамилия, номерПаспорта);
        }
    }

    // «Задолженность» — тот же абонент, дополненный полем «Долг по оплате».
    class Задолженность : Абонент
    {
        private double долг;
        public Задолженность(int номерТелефона, string фамилия, long номерПаспорта, double долг) : base(номерТелефона, фамилия, номерПаспорта)
        {
            this.долг = долг;
        }
        // Поле долг закрытое, а сравнивать долги нужно в Main,
        // поэтому значение отдаётся через отдельный метод.
        public double ПолучитьДолг()
        {
            return долг;
        }
        // Вывод переопределён через new (скрытие метода базового класса):
        // сначала печатаются данные абонента методом базового класса,
        // затем — долг.
        public new void Показать()
        {
            base.Показать();
            Console.WriteLine("Долг по оплате: {0:f2}", долг);
        }
    }

    class Program
    {
        static void Main(string[] args)
        {
            // Таблица абонентов задаётся в коде, как список фигур в примере
            // «Геометрия»: так результат одинаков при каждом запуске.
            Задолженность[] абоненты = new Задолженность[5];
            абоненты[0] = new Задолженность(2345671, "Иванов", 4510123456, 350.50);
            абоненты[1] = new Задолженность(3456782, "Петров", 4511234567, 1520.75);
            абоненты[2] = new Задолженность(4567893, "Сидорова", 4512345678, 0.0);
            абоненты[3] = new Задолженность(5678904, "Кузнецов", 4513456789, 980.00);
            абоненты[4] = new Задолженность(6789015, "Смирнова", 4514567890, 1210.30);
            Console.WriteLine("Все абоненты:");
            for (int i = 0; i < абоненты.Length; i++) абоненты[i].Показать();
            // Обычный поиск максимума: берём первого абонента и сравниваем
            // с ним остальных. При равных долгах остаётся тот, кто раньше.
            Задолженность должник = абоненты[0];
            for (int i = 1; i < абоненты.Length; i++)
                if (абоненты[i].ПолучитьДолг() > должник.ПолучитьДолг()) должник = абоненты[i];
            Console.WriteLine();
            Console.WriteLine("Абонент с максимальным долгом по оплате:");
            должник.Показать();
        }
    }
}
