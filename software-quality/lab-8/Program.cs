// ЛР8, метрики Абреу (MOOD). Вариант 1, задача 1:
// базовый класс «Сетевое напряжение» (U, faza) и два наследника —
// «Электроустановка на 220 В» (type, wt) и «Трёхфазная электроустановка
// на 360 В» (type, R, amp). Виртуальный метод печати базового класса
// переопределён в наследниках; объекты хранятся в массиве ссылок на
// базовый класс в том порядке, в каком их ввёл пользователь.
//
// Номера строк в README.md считаются по тексту без комментариев и пустых
// строк (таблица «Текст программы»).
using System;

namespace Lab8
{
    // Базовый класс. Поля protected, как у класса Точка в примере
    // методички: наследникам напряжение нужно для расчёта тока.
    class СетевоеНапряжение
    {
        protected double U;
        protected int faza;
        public СетевоеНапряжение(double U, int faza)
        {
            this.U = U; this.faza = faza;
        }
        // Виртуальный метод печати (требование б): выводит параметры сети.
        public virtual void Печать()
        {
            Console.WriteLine("Сеть: U = {0} В, фаз: {1}", U, faza);
        }
    }

    // Однофазная установка на 220 В. Пользователь задаёт тип и мощность,
    // ток и сопротивление получаются из мощности: I = W / U, R = U / I.
    class Электроустановка220 : СетевоеНапряжение
    {
        private string type;
        private double wt;
        public Электроустановка220(string type, double wt) : base(220, 1)
        {
            this.type = type; this.wt = wt;
        }
        public override void Печать()
        {
            double I = wt / U;
            base.Печать();
            Console.WriteLine("  {0}: W = {1:f2} Вт, I = W / U = {2:f3} А, R = U / I = {3:f2} Ом",
                type, wt, I, U / I);
        }
    }

    // Трёхфазная установка на 360 В (напряжение взято из условия задачи).
    // Пользователь задаёт тип и сопротивление, потребляемый ток amp
    // считается в конструкторе по закону Ома: I = U / R.
    class Электроустановка360 : СетевоеНапряжение
    {
        private string type;
        private double R, amp;
        public Электроустановка360(string type, double R) : base(360, 3)
        {
            this.type = type; this.R = R;
            amp = U / R;
        }
        public override void Печать()
        {
            base.Печать();
            Console.WriteLine("  {0}: R = {1:f2} Ом, I = U / R = {2:f3} А, W = I * U = {3:f2} Вт",
                type, R, amp, amp * U);
        }
    }

    class Program
    {
        public static void Main()
        {
            int n, вид;
            string type;
            Console.Write("Количество электроустановок: ");
            n = int.Parse(Console.ReadLine());
            // Массив ссылок на базовый класс (требование в): в нём лежат
            // объекты обоих наследников вперемешку.
            СетевоеНапряжение[] список = new СетевоеНапряжение[n];
            for (int i = 0; i < n; i++)
            {
                Console.Write("Установка {0}: вид (1 - на 220 В, 2 - трехфазная на 360 В) -> ", i);
                вид = int.Parse(Console.ReadLine());
                Console.Write("Установка {0}: тип -> ", i);
                type = Console.ReadLine();
                // Объект создаётся конструктором с начальными значениями
                // полей (требование г).
                if (вид == 1)
                {
                    Console.Write("Установка {0}: мощность W, Вт -> ", i);
                    список[i] = new Электроустановка220(type, double.Parse(Console.ReadLine()));
                }
                else
                {
                    Console.Write("Установка {0}: сопротивление R, Ом -> ", i);
                    список[i] = new Электроустановка360(type, double.Parse(Console.ReadLine()));
                }
            }
            // Вывод через массив ссылок и цикл (требование д). Какой Печать()
            // вызовется, решается по реальному типу объекта — метод виртуальный.
            Console.WriteLine();
            for (int i = 0; i < список.Length; i++)
                список[i].Печать();
        }
    }
}
