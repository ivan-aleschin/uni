// ЛР6, метрики Чидамбера и Кемерера. Вариант 1, задача 1:
// определить понятие «Точка» (координаты по осям абсцисс и ординат),
// на его основе определить понятие «Квадрат» — через точку левого верхнего
// угла и размер стороны. Изменить размер стороны на заданную величину DR
// и вычислить площадь квадрата после изменения.
//
// Устроено так же, как пример «Геометрия окружности и прямоугольника»
// из методички: базовый класс Точка, наследник Квадрат и основной класс Program.
using System;
namespace Lab6
{
    // Базовый класс. Поля protected, чтобы наследник мог их читать
    // (в примере методички у класса Точка сделано так же).
    class Точка
    {
        protected double x, y;
        public Точка(double x, double y)
        {
            this.x = x; this.y = y;
        }
        public void Показать()
        {
            Console.WriteLine("Точка ({0:f2}; {1:f2})", x, y);
        }
    }
    // Квадрат «базируется на точке»: координаты левого верхнего угла
    // он наследует от Точки, а свою у него только сторона a.
    class Квадрат : Точка
    {
        private double a;
        public Квадрат(double x, double y, double a) : base(x, y)
        {
            this.a = a;
        }
        // DR может быть и отрицательным — тогда квадрат уменьшается
        public void ИзменитьРазмер(double dr)
        {
            a = a + dr;
        }
        public double Площадь()
        {
            return a * a;
        }
        // Метод вывода скрывает (new) метод базового класса, как в примере
        // методички: какой из двух вызовется, решает тип ссылки.
        public new void Показать()
        {
            Console.WriteLine("Квадрат: угол ({0:f2}; {1:f2}) сторона={2:f2} площадь={3:f2}", x, y, a, Площадь());
        }
    }
    class Program
    {
        static void Main(string[] args)
        {
            double x, y, a, dr;
            Console.Write("X левого верхнего угла: ");
            x = double.Parse(Console.ReadLine());
            Console.Write("Y левого верхнего угла: ");
            y = double.Parse(Console.ReadLine());
            Console.Write("Сторона квадрата: ");
            a = double.Parse(Console.ReadLine());
            Console.Write("Изменение стороны DR: ");
            dr = double.Parse(Console.ReadLine());
            Console.WriteLine();
            // сторона должна быть положительной и до изменения, и после него,
            // иначе квадрата не существует и площадь считать бессмысленно
            if (a <= 0 || a + dr <= 0)
            {
                Console.WriteLine("Сторона квадрата должна быть больше нуля до и после изменения");
                return;
            }
            Квадрат квадрат = new Квадрат(x, y, a);
            // ссылка типа Точка — вызывается метод базового класса,
            // печатается только левый верхний угол
            ((Точка)квадрат).Показать();
            квадрат.Показать();
            квадрат.ИзменитьРазмер(dr);
            квадрат.Показать();
            Console.WriteLine("Площадь квадрата после изменения стороны на DR = {0:f2}: {1:f2}", dr, квадрат.Площадь());
        }
    }
}
