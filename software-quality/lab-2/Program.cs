// ЛР2, метрики Джилба. Вариант 1, задача 18:
// вычислить значения функции
//   f(x) = sin(pi/2)            при x <= 0.5,
//   f(x) = sin((x - 1) * pi/2)  при x >  0.5
// для x от -0.4 до 1.3 с шагом 0.1.
//
// Комментарии в подсчёт операторов не входят: листинг в README.md
// приведён без них, номера строк в таблицах относятся к нему.
using System;
class Program
{
    // Сама функция вынесена в отдельный модуль (метод), чтобы Main
    // занимался только перебором аргументов и выводом таблицы.
    static double F(double x)
    {
        if (x <= 0.5)
            return Math.Sin(Math.PI / 2);
        else
            return Math.Sin((x - 1) * Math.PI / 2);
    }
    static void Main()
    {
        Console.WriteLine("    x       f(x)");
        // Шаг по x задаём через целый счётчик k: x = k / 10.
        // Если прибавлять 0.1 к double, копится ошибка округления,
        // и точка x = 0.5 может превратиться в 0.5000000001 и уйти
        // не в ту ветку, а последняя точка 1.3 — вообще выпасть.
        for (int k = -4; k <= 13; k++)
        {
            double x = k / 10.0;
            Console.WriteLine("{0,5:f1}  {1,9:f4}", x, F(x));
        }
    }
}
