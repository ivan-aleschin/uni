// ЛР4, метрика Маккейба. Вариант 1, задача 7:
// вывести на экран все натуральные шестизначные числа из диапазона [A, B],
// у которых сумма трёх младших цифр равна сумме трёх старших.
// Если таких чисел нет, вывести «Требуемых чисел нет».
// Границы A и B вводятся с клавиатуры.
//
// Номера в комментариях вида «вершина N» — это номера вершин
// управляющего графа из README.md.
using System;
class Program
{
    static void Main()
    {
        int a, b, from, to, i, high, low, sumHigh, sumLow;
        bool found;

        // вершина 1: ввод и подготовка.
        // Вместо отдельных if для «подрезки» диапазона берём Math.Max/Min:
        // шестизначные числа лежат в [100000, 999999], и так мы сразу
        // пересекаем с ним диапазон пользователя без лишних ветвлений.
        Console.Write("A = ");
        a = int.Parse(Console.ReadLine());
        Console.Write("B = ");
        b = int.Parse(Console.ReadLine());
        from = Math.Max(a, 100000);
        to = Math.Min(b, 999999);
        found = false;

        // вершина 2 — проверка i <= to, вершина 6 — i++
        for (i = from; i <= to; i++)
        {
            // вершина 3: делим число на две тройки цифр.
            // 123456 / 1000 = 123 (старшие), 123456 % 1000 = 456 (младшие).
            high = i / 1000;
            low = i % 1000;
            sumHigh = high / 100 + high / 10 % 10 + high % 10;
            sumLow = low / 100 + low / 10 % 10 + low % 10;
            // вершина 4: сравнение сумм, вершина 5: вывод найденного числа
            if (sumHigh == sumLow)
            {
                Console.WriteLine(i);
                found = true;
            }
        }

        // вершина 7: было ли найдено хоть одно число; вершина 8: сообщение
        if (!found)
            Console.WriteLine("Требуемых чисел нет");
        // вершина 9: конец программы
    }
}
