// ЛР1, метрики Холстеда. Вариант 1, задача 1:
// написать и протестировать функцию, которая «переворачивает» строку,
// переданную ей параметром, в зеркальное состояние.
//
// Комментарии в расчёт метрик не входят: листинг в README.md приведён
// без них, и номера строк в таблицах относятся именно к тому листингу.
using System;
class Program
{
    // Идём по строке с последнего символа к первому и дописываем
    // символы в результат. Для пустой строки цикл не выполнится ни разу
    // и вернётся пустая строка — отдельно этот случай проверять не надо.
    static string Reverse(string s)
    {
        string result = "";
        for (int i = s.Length - 1; i >= 0; i--)
            result += s[i];
        return result;
    }
    // Тестирование: пользователь вводит строки, программа печатает
    // перевёрнутый вариант, пока на вопрос о продолжении отвечают «y».
    static void Main()
    {
        string text;
        char answer;
        do
        {
            Console.Write("Введите строку: ");
            text = Console.ReadLine();
            Console.WriteLine("Зеркальная строка: " + Reverse(text));
            Console.Write("Проверить ещё одну строку? (y/n): ");
            answer = char.Parse(Console.ReadLine());
        } while (answer == 'y' || answer == 'Y');
    }
}
